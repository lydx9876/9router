// ── 32 位旋转 ────────────────────────────────────────────────────────────

/**
 * 左循环移位（32 位）。
 *
 * ⚠️ 这里**不能**先把 x 转成无符号（x >>> 0）再左移。
 * SM4 的 L 变换是 `b ^ rotl(b,2) ^ rotl(b,10) ^ ...` 的链式异或，
 * JS 的 ^ 返回**有符号** 32 位整数；当中间结果最高位为 1 时它是负数，
 * 而负数的 `x << n` 与 `x >>> (32-n)` 恰好实现了所需的模 2^32 回绕。
 * 若先把 x 归一成无符号数，反而会改变这些中间值，密文全错
 * （GB/T 32907-2016 测试向量会从 681edf34… 变成 79bc3df8…）。
 */
function rotl(x, n) {
  return ((x << n) | (x >>> (32 - n))) >>> 0;
}

/** 非线性变换 τ：S 盒逐字节替换 */
function tau(x) {
  // 每个字节左移后可能溢出成负数，必须逐项 & 0xff 再拼，
  // 否则按位运算会把符号位带进后续的 L / L' 变换。
  return (
    ((SBOX[(x >>> 24) & 0xff] << 24) |
     (SBOX[(x >>> 16) & 0xff] << 16) |
     (SBOX[(x >>> 8) & 0xff] << 8) |
     SBOX[x & 0xff]) >>> 0
  );
}

/** 线性变换 L：B 变换 */
function lTransform(b) {
  // ⚠️ 不能写成逐步归一（r = (r ^ rotl(r,n)) >>> 0; 循环）——
  // 见 rotl() 的说明：链式异或的有符号传播是 SM4 标准的一部分。
  return (b ^ rotl(b, 2) ^ rotl(b, 10) ^ rotl(b, 18) ^ rotl(b, 24)) >>> 0;
}

/** 线性变换 L′：C 变换 */
function lPrime(c) {
  return (c ^ rotl(c, 13) ^ rotl(c, 23)) >>> 0;
}

// ── 密钥扩展 ────────────────────────────────────────────────────────────

/**
 * 生成 32 个轮密钥。
 *
 * @param {Uint8Array} key 16 字节
 * @returns {Uint32Array} 32 个轮密钥
 */
function expandKey(key) {
  if (key.length !== 16) {
    throw new Error(`SM4 key must be 16 bytes, got ${key.length}`);
  }

  const k = new Uint32Array(32);
  // K[0..3] = MK[0..3] ^ FK[0..3]
  const words = new Uint32Array(36);
  for (let i = 0; i < 4; i++) {
    const word = ((key[4 * i] << 24) | (key[4 * i + 1] << 16) |
                  (key[4 * i + 2] << 8) | key[4 * i + 3]) >>> 0;
    words[i] = (word ^ FK[i]) >>> 0;
  }

  // K[i+4] = K[i] ^ L'(τ(K[i+1] ^ K[i+2] ^ K[i+3] ^ CK[i]))
  for (let i = 0; i < 32; i++) {
    const t = words[i] ^ lPrime(tau(words[i + 1] ^ words[i + 2] ^ words[i + 3] ^ CK[i]));
    words[i + 4] = t >>> 0;
    k[i] = words[i + 4];
  }
  return k;
}

// ── 分组加密 ────────────────────────────────────────────────────────────

/**
 * SM4 单块加密（16 字节 → 16 字节）。
 *
 * @param {Uint8Array} block 16 字节明文
 * @param {Uint32Array} roundKeys expandKey 的输出
 * @returns {Uint8Array} 16 字节密文
 */
function encryptBlock(block, roundKeys) {
  const x = new Uint32Array(36);
  for (let i = 0; i < 4; i++) {
    x[i] = ((block[4 * i] << 24) | (block[4 * i + 1] << 16) |
             (block[4 * i + 2] << 8) | block[4 * i + 3]) >>> 0;
  }

  for (let i = 0; i < 32; i++) {
    x[i + 4] = (x[i] ^ lTransform(tau((x[i + 1] ^ x[i + 2] ^ x[i + 3] ^ roundKeys[i])))) >>> 0;
  }

  // 反序输出（RK35, RK34, RK33, RK32）
  const out = new Uint8Array(16);
  for (let i = 0; i < 4; i++) {
    const v = x[35 - i];
    out[4 * i] = (v >>> 24) & 0xff;
    out[4 * i + 1] = (v >>> 16) & 0xff;
    out[4 * i + 2] = (v >>> 8) & 0xff;
    out[4 * i + 3] = v & 0xff;
  }
  return out;
}

/**
 * SM4 分组加密（多块）。padding 由调用方处理（GCM 用 CTR，不需要 padding）。
 *
 * @param {Uint8Array} data
 * @param {Uint32Array} roundKeys
 * @returns {Uint8Array}
 */
function encryptBlocks(data, roundKeys) {
  const out = new Uint8Array(data.length);
  for (let off = 0; off < data.length; off += 16) {
    out.set(encryptBlock(data.subarray(off, off + 16), roundKeys), off);
  }
  return out;
}

